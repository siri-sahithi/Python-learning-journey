import numpy as np
mat1=np.matrix([[1,2,3],[4,5,6],[7,8,9]])
print("The given matrix :\n",mat1)
mat2=np.delete(mat1,1,axis=0)
print(mat2)
mat3=np.delete(mat1,1,axis=1)
print(mat3)
